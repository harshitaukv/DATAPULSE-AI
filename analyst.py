import streamlit as st

from components.session import call, can, client
from components.theme import ACCENT, BAD, EXTRACT, LOAD, MUTED, OK, TRANSFORM, VALIDATE, WARN
from components.ui import (card, empty_state, esc, facts, fmt_int, fmt_time, html_line, page_header, panel, section,
                           severity_badge, short)

c = client()
_status = call(c.get, "/api/v1/assistant/status", quiet=True) or {}
_llm, _rag = _status.get("llm", {}), _status.get("rag", {})
page_header("AI incident analyst", "Explanations grounded in the stored evidence and the troubleshooting "
            "knowledge base. Measured facts and model hypotheses are kept separate.", tone="transform",
            chips=[(_llm.get("model") if _llm.get("configured") else "rule-based", "explanations", "#FFFFFF"),
                   (fmt_int(_rag.get("documents")), "guides indexed", EXTRACT),
                   (fmt_int(_rag.get("chunks")), "searchable sections", LOAD)])
items = (call(c.get, "/api/v1/incidents", limit=200) or {}).get("items", [])
if not items:
    empty_state("No incidents to analyse", "Run a pipeline on a sample with problems to create one.")
    st.stop()

ids = [i["id"] for i in items]
default = ids.index(st.session_state["selected_incident"]) if st.session_state.get("selected_incident") in ids else 0
labels = {i["id"]: f"{short(i['id'])} · {i['severity']} · {i['title']}" for i in items}
incident_id = st.selectbox("Incident", ids, index=default, format_func=labels.get)
st.session_state["selected_incident"] = incident_id
inc = call(c.get, f"/api/v1/incidents/{incident_id}")
if not inc:
    st.stop()

llm = _llm
mode_text = f"LLM: {llm.get('provider')} / {llm.get('model')}" if llm.get("configured") else \
    "No LLM configured: rule-based summaries are used and labelled as such"
html_line(f"<div class='dp-panel' style='--c:{TRANSFORM};--t:rgba(238,70,188,.07)'>"
          f"<div class='t'>Selected incident</div><div class='b'>{severity_badge(inc['severity'])} <b>{esc(inc['title'])}</b>"
          f"<br><span style='color:{MUTED};font-size:.84rem'>{esc(inc['incident_type'].replace('_', ' '))} · "
          f"run {short(inc['run_id'])} · {esc(mode_text)}</span></div></div>")

analysis = inc.get("ai_analysis") or {}
if st.button("Analyse incident" if not analysis else "Re-run analysis", type="primary",
             disabled=not can("analyze_incident")):
    with st.spinner("Retrieving documentation and analysing evidence…"):
        updated = call(c.post, f"/api/v1/incidents/{incident_id}/analyze")
    if updated:
        analysis = updated["ai_analysis"]

if analysis:
    d = analysis["diagnosis"]
    source = analysis.get("source")
    label = (f"Generated by {analysis.get('model')}" if source == "llm"
             else "Rule-based summary (no LLM response was used)")
    html_line(f"<span style='color:{MUTED};font-size:.84rem'>{label} · {fmt_time(analysis.get('generated_at'))}</span>")
    if analysis.get("llm_error"):
        st.warning(f"The LLM could not be used: {analysis['llm_error']}")
    if analysis.get("unverified_numbers"):
        st.warning("The model mentioned numbers that do not appear in the evidence: "
                   + ", ".join(analysis["unverified_numbers"]) + ". Treat those statements with caution.")

    panel("Summary", d["incident_summary"], ACCENT)
    left, right = st.columns([1, 1])
    with left, st.container(border=True):
        section("Confirmed by the system", "from stored run records", LOAD)
        facts(analysis.get("system_confirmed_facts", []))
        if source == "llm":
            section("Evidence cited by the model", "", EXTRACT)
            facts(d["confirmed_evidence"])
    with right, st.container(border=True):
        panel("Probable cause (hypothesis)", d["probable_cause"], WARN)
        panel("Recommended action", d["recommended_action"], OK)
        panel("Uncertainty", d["uncertainty"], MUTED)
        mr = d["requires_manual_review"]
        html_line(f"Manual review required: <span class='dp-badge' style='--c:{BAD if mr else OK};"
                  f"--t:{'rgba(240,68,56,.12)' if mr else 'rgba(18,183,106,.12)'}'>{'yes' if mr else 'no'}</span>")

    docs = analysis.get("retrieved_documents", [])
    retrieval = analysis.get("retrieval", {})
    with st.expander(f"Retrieved documentation ({len(docs)})"):
        if not docs:
            st.write("No document passed the relevance threshold for this incident.")
        for doc in docs:
            st.markdown(f"**{doc['title']}** · {doc['section']} · similarity {doc['score']}")
            st.caption(doc["text"][:700] + ("…" if len(doc["text"]) > 700 else ""))
        st.caption(f"Retrieval backend: {retrieval.get('backend')}, threshold {retrieval.get('threshold')}.")
else:
    section("How the analysis works", "run it to fill in the panels below", TRANSFORM)
    hw = st.columns(3)
    for col, (t, b, colr, ic) in zip(hw, (
            ("1. Collect evidence", "Reads the stored run: failed stage, error, check results and record counts.",
             EXTRACT, "🧾"),
            ("2. Retrieve guides", "Searches the troubleshooting knowledge base for sections that match the incident.",
             VALIDATE, "📚"),
            ("3. Explain", "Writes a summary, a probable cause and a recommended action, and flags any number it "
             "cannot verify.", TRANSFORM, "💡"))):
        with col:
            card(t, b, colr, ic)

section("Ask about this incident", "pick a starter question or type your own", VALIDATE)
history_key = f"chat_{incident_id}"
history = st.session_state.setdefault(history_key, [])
suggestions = ["🔍 Why did the pipeline fail?", "🧪 Which validation checks failed?",
               "📊 What changed compared with the previous run?", "🩹 How can this issue be resolved?",
               "🕘 Has this happened before?", "📚 What does the documentation recommend?"]
cols = st.columns(3)
clicked = None
for i, s in enumerate(suggestions):
    if cols[i % 3].button(s, key=f"sug_{i}", width="stretch"):
        clicked = s.split(" ", 1)[1]

for m in history:
    with st.chat_message(m["role"]):
        st.markdown(m["content"])
        if m.get("meta"):
            st.caption(m["meta"])

question = st.chat_input("Ask a question about this incident") or clicked
if question:
    history.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)
    with st.chat_message("assistant"):
        with st.spinner("Searching records and documentation…"):
            res = call(c.post, "/api/v1/assistant/chat",
                       {"question": question, "incident_id": incident_id,
                        "history": [{"role": h["role"], "content": h["content"]} for h in history[:-1]][-6:]})
        if res:
            meta = ("LLM answer" if res["mode"] == "llm" else "Rule-based answer") + \
                   (" · sources: " + "; ".join(f"{s['title']} ({s['section']})" for s in res["sources"][:3])
                    if res["sources"] else " · no relevant document found")
            st.markdown(res["answer"])
            st.caption(meta)
            history.append({"role": "assistant", "content": res["answer"], "meta": meta})
